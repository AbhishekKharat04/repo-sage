def gen_dockerfile(stack: list, project_type: str, files: list) -> str:
    """Generate an optimized multi-stage Dockerfile."""
    lang = _detect_primary_lang(stack)
    templates = {
        "python": _dockerfile_python(files),
        "node": _dockerfile_node(files),
        "go": _dockerfile_go(files),
        "java": _dockerfile_java(),
        "rust": _dockerfile_rust(),
    }
    df = templates.get(lang, _dockerfile_python(files))
    return f"# === Dockerfile ===\n# Generated by ShipSage — AI DevOps Pipeline Generator\n# Optimized multi-stage build for {lang}\n\n{df}"


def gen_compose(stack: list, files: list) -> str:
    """Generate docker-compose.yml with detected services."""
    lang = _detect_primary_lang(stack)
    port = {"python": "8000", "node": "3000", "go": "8080", "java": "8080", "rust": "8080"}.get(lang, "8000")
    services = f"""# === docker-compose.yml ===
# Generated by ShipSage

version: '3.9'

services:
  app:
    build: .
    container_name: app
    ports:
      - "{port}:{port}"
    env_file: .env
    restart: unless-stopped
    depends_on:"""

    db_services = ""
    has_pg = any(k in stack for k in ["PostgreSQL", "Django", "SQLAlchemy"])
    has_mongo = "MongoDB" in stack or any("mongo" in f.lower() for f in files)
    has_redis = "Redis" in stack or any("redis" in f.lower() for f in files)

    deps = []
    if has_pg:
        deps.append("postgres")
        db_services += """
  postgres:
    image: postgres:16-alpine
    container_name: postgres
    environment:
      POSTGRES_USER: \${DB_USER:-app}
      POSTGRES_PASSWORD: \${DB_PASS:-secret}
      POSTGRES_DB: \${DB_NAME:-appdb}
    ports:
      - "5432:5432"
    volumes:
      - pg_data:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U app"]
      interval: 10s
      retries: 5"""

    if has_mongo:
        deps.append("mongo")
        db_services += """
  mongo:
    image: mongo:7
    container_name: mongo
    environment:
      MONGO_INITDB_ROOT_USERNAME: \${MONGO_USER:-root}
      MONGO_INITDB_ROOT_PASSWORD: \${MONGO_PASS:-secret}
    ports:
      - "27017:27017"
    volumes:
      - mongo_data:/data/db"""

    if has_redis:
        deps.append("redis")
        db_services += """
  redis:
    image: redis:7-alpine
    container_name: redis
    ports:
      - "6379:6379"
    volumes:
      - redis_data:/data"""

    if deps:
        services += "\n" + "\n".join(f"      {d}:\n        condition: service_started" for d in deps)
    else:
        services += " []"

    services += "\n    networks:\n      - app-network"
    db_services_with_net = ""
    for line in db_services.split("\n"):
        db_services_with_net += line + "\n"

    volumes = "\nvolumes:"
    if has_pg: volumes += "\n  pg_data:"
    if has_mongo: volumes += "\n  mongo_data:"
    if has_redis: volumes += "\n  redis_data:"
    if not any([has_pg, has_mongo, has_redis]): volumes += " {}"

    return f"""{services}
{db_services}

networks:
  app-network:
    driver: bridge
{volumes}"""


