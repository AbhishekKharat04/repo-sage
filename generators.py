def gen_cicd(stack: list, files: list) -> str:
    """Generate GitHub Actions CI/CD pipeline with AWS ECR + EKS deploy."""
    lang = _detect_primary_lang(stack)
    has_tests = any("test" in f.lower() for f in files)
    test_cmd = {"python": "pytest", "node": "npm test", "go": "go test ./...", "java": "mvn test"}.get(lang, "echo 'No tests'")
    build_cmd = {"python": "pip install -r requirements.txt", "node": "npm ci", "go": "go build ./...", "java": "mvn package"}.get(lang, "echo 'Build'")

    return f"""# === GitHub Actions CI/CD Pipeline ===
# Generated by ShipSage — Build → Test → Push to ECR → Deploy to EKS

name: CI/CD Pipeline

on:
  push:
    branches: [main, develop]
  pull_request:
    branches: [main]

env:
  AWS_REGION: us-east-1
  ECR_REPOSITORY: app
  EKS_CLUSTER: app-cluster
  IMAGE_TAG: ${{{{ github.sha }}}}

jobs:
  # ── Stage 1: Lint & Test ──
  test:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - name: Setup environment
        uses: {"actions/setup-python@v5\\n        with:\\n          python-version: '3.12'" if lang == "python" else "actions/setup-node@v4\\n        with:\\n          node-version: '20'" if lang == "node" else "actions/setup-go@v5\\n        with:\\n          go-version: '1.22'" if lang == "go" else "actions/setup-java@v4\\n        with:\\n          java-version: '21'"}

      - name: Install dependencies
        run: {build_cmd}

      - name: Run tests
        run: {test_cmd if has_tests else "echo 'No test suite detected — add tests!'"}

  # ── Stage 2: Build & Push Docker Image ──
  build:
    needs: test
    runs-on: ubuntu-latest
    if: github.ref == 'refs/heads/main'
    permissions:
      id-token: write
      contents: read
    steps:
      - uses: actions/checkout@v4

      - name: Configure AWS Credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: ${{{{ secrets.AWS_ROLE_ARN }}}}
          aws-region: ${{{{ env.AWS_REGION }}}}

      - name: Login to Amazon ECR
        id: ecr
        uses: aws-actions/amazon-ecr-login@v2

      - name: Build & Push Docker Image
        run: |
          docker build -t ${{{{ steps.ecr.outputs.registry }}}}/${{{{ env.ECR_REPOSITORY }}}}:${{{{ env.IMAGE_TAG }}}} .
          docker push ${{{{ steps.ecr.outputs.registry }}}}/${{{{ env.ECR_REPOSITORY }}}}:${{{{ env.IMAGE_TAG }}}}

  # ── Stage 3: Deploy to EKS ──
  deploy:
    needs: build
    runs-on: ubuntu-latest
    if: github.ref == 'refs/heads/main'
    steps:
      - uses: actions/checkout@v4

      - name: Configure AWS Credentials
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: ${{{{ secrets.AWS_ROLE_ARN }}}}
          aws-region: ${{{{ env.AWS_REGION }}}}

      - name: Update kubeconfig
        run: aws eks update-kubeconfig --name ${{{{ env.EKS_CLUSTER }}}} --region ${{{{ env.AWS_REGION }}}}

      - name: Deploy to Kubernetes
        run: |
          kubectl set image deployment/app app=${{{{ steps.ecr.outputs.registry }}}}/${{{{ env.ECR_REPOSITORY }}}}:${{{{ env.IMAGE_TAG }}}} -n app-production
          kubectl rollout status deployment/app -n app-production --timeout=300s"""


